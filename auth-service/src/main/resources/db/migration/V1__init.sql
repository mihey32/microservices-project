CREATE TABLE accounts
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email              VARCHAR(255)                            NOT NULL,
    password_hash      VARCHAR(255),
    role               VARCHAR(255)                            NOT NULL,
    created_at         TIMESTAMP with time zone                NOT NULL,
    updated_at         TIMESTAMP with time zone                NOT NULL,
    email_verified     BOOLEAN                                 NOT NULL,
    blocked            BOOLEAN                                 NOT NULL,
    oauth2_provider    VARCHAR(255),
    oauth2_provider_id VARCHAR(255),
    CONSTRAINT pk_accounts PRIMARY KEY (id)
);

CREATE TABLE email_verification_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_id BIGINT                                  NOT NULL,
    token_hash VARCHAR(255)                            NOT NULL,
    expires_at TIMESTAMP with time zone                NOT NULL,
    used       BOOLEAN                                 NOT NULL,
    created_at TIMESTAMP with time zone                NOT NULL,
    CONSTRAINT pk_email_verification_tokens PRIMARY KEY (id)
);

CREATE TABLE password_reset_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_id BIGINT                                  NOT NULL,
    token_hash VARCHAR(255)                            NOT NULL,
    expires_at TIMESTAMP with time zone                NOT NULL,
    used       BOOLEAN                                 NOT NULL,
    created_at TIMESTAMP with time zone                NOT NULL,
    CONSTRAINT pk_password_reset_tokens PRIMARY KEY (id)
);

CREATE TABLE refresh_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_id BIGINT                                  NOT NULL,
    created_at TIMESTAMP with time zone                NOT NULL,
    token_hash VARCHAR(255)                            NOT NULL,
    expires_at TIMESTAMP with time zone                NOT NULL,
    revoked    BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_refresh_tokens PRIMARY KEY (id)
);

ALTER TABLE accounts
    ADD CONSTRAINT UC_ACCOUNTS_EMAIL UNIQUE (email);

ALTER TABLE email_verification_tokens
    ADD CONSTRAINT UC_EMAIL_VERIFICATION_TOKENS_TOKEN_HASH UNIQUE (token_hash);

ALTER TABLE password_reset_tokens
    ADD CONSTRAINT UC_PASSWORD_RESET_TOKENS_TOKEN_HASH UNIQUE (token_hash);

ALTER TABLE refresh_tokens
    ADD CONSTRAINT UC_REFRESH_TOKENS_TOKEN_HASH UNIQUE (token_hash);

CREATE INDEX idx_account_oauth ON accounts (oauth2_provider, oauth2_provider_id);

CREATE INDEX idx_refresh_tokens_account_id ON refresh_tokens (account_id);

CREATE INDEX idx_reset_tokens_account_id ON password_reset_tokens (account_id);

CREATE INDEX idx_verification_tokens_account_id ON email_verification_tokens (account_id);